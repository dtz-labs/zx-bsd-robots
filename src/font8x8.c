/*
 * Based on Daniel Hepper's font8x8_basic public-domain VGA font:
 * https://github.com/dhepper/font8x8
 *
 * The upstream rows store the leftmost pixel in bit 0.  R() reverses each
 * constant at compile time, so the table stored in the program is ready for
 * the Timex display's bit-7-left convention and needs no run-time conversion.
 * The six frame characters are local UI glyphs with joined, square corners.
 */
#define R(byte_) ((uint8_t)( \
    ((((unsigned int)(byte_)) & 0x01u) << 7) | \
    ((((unsigned int)(byte_)) & 0x02u) << 5) | \
    ((((unsigned int)(byte_)) & 0x04u) << 3) | \
    ((((unsigned int)(byte_)) & 0x08u) << 1) | \
    ((((unsigned int)(byte_)) & 0x10u) >> 1) | \
    ((((unsigned int)(byte_)) & 0x20u) >> 3) | \
    ((((unsigned int)(byte_)) & 0x40u) >> 5) | \
    ((((unsigned int)(byte_)) & 0x80u) >> 7)))

#define GLYPH(a_, b_, c_, d_, e_, f_, g_, h_) \
    R(a_), R(b_), R(c_), R(d_), R(e_), R(f_), R(g_), R(h_)
#define SCREEN_GLYPH(a_, b_, c_, d_, e_, f_, g_, h_) \
    (uint8_t)(a_), (uint8_t)(b_), (uint8_t)(c_), (uint8_t)(d_), \
    (uint8_t)(e_), (uint8_t)(f_), (uint8_t)(g_), (uint8_t)(h_)

